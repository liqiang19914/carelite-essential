-- HMS 官网投放归因与转化事件。
-- 浏览器不直接写表：公开 Edge Function 校验来源和字段后使用 service_role 写入；
-- 只有平台管理员可以读取统计，避免匿名访问明细泄露。

CREATE TABLE IF NOT EXISTS public.landing_conversion_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_type text NOT NULL CHECK (event_type IN ('page_view', 'wecom_click', 'lead_submit')),
  visitor_id text NOT NULL CHECK (char_length(visitor_id) BETWEEN 8 AND 100),
  session_id text NOT NULL CHECK (char_length(session_id) BETWEEN 8 AND 100),
  page_url text NOT NULL DEFAULT '',
  referrer text NOT NULL DEFAULT '',
  utm_source text NOT NULL DEFAULT 'direct',
  utm_medium text NOT NULL DEFAULT '',
  utm_campaign text NOT NULL DEFAULT '',
  utm_content text NOT NULL DEFAULT '',
  utm_term text NOT NULL DEFAULT '',
  cta_source text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS landing_conversion_events_created_at_idx
  ON public.landing_conversion_events (created_at DESC);

CREATE INDEX IF NOT EXISTS landing_conversion_events_channel_idx
  ON public.landing_conversion_events (utm_source, utm_campaign, created_at DESC);

CREATE INDEX IF NOT EXISTS landing_conversion_events_visitor_idx
  ON public.landing_conversion_events (visitor_id, created_at DESC);

ALTER TABLE public.landing_conversion_events ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Platform admins can read landing conversion events"
  ON public.landing_conversion_events;
CREATE POLICY "Platform admins can read landing conversion events"
  ON public.landing_conversion_events
  FOR SELECT
  TO authenticated
  USING (public.is_admin(auth.uid()));

REVOKE ALL ON TABLE public.landing_conversion_events FROM anon;
GRANT SELECT ON TABLE public.landing_conversion_events TO authenticated;

CREATE OR REPLACE FUNCTION public.admin_get_landing_conversion_stats(
  p_from timestamptz,
  p_to timestamptz
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  result jsonb;
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_admin(auth.uid()) THEN
    RAISE EXCEPTION 'permission denied';
  END IF;

  IF p_from IS NULL OR p_to IS NULL OR p_from >= p_to THEN
    RAISE EXCEPTION 'invalid time range';
  END IF;

  WITH filtered AS (
    SELECT
      event_type,
      visitor_id,
      COALESCE(NULLIF(utm_source, ''), 'direct') AS source,
      COALESCE(utm_medium, '') AS medium,
      COALESCE(utm_campaign, '') AS campaign,
      created_at
    FROM public.landing_conversion_events
    WHERE created_at >= p_from AND created_at < p_to
  ),
  totals AS (
    SELECT
      COUNT(DISTINCT visitor_id)::bigint AS visitors,
      COUNT(*) FILTER (WHERE event_type = 'page_view')::bigint AS page_views,
      COUNT(*) FILTER (WHERE event_type = 'wecom_click')::bigint AS wecom_clicks,
      COUNT(*) FILTER (WHERE event_type = 'lead_submit')::bigint AS lead_submits
    FROM filtered
  ),
  channels AS (
    SELECT
      source,
      medium,
      campaign,
      COUNT(DISTINCT visitor_id)::bigint AS visitors,
      COUNT(*) FILTER (WHERE event_type = 'page_view')::bigint AS page_views,
      COUNT(*) FILTER (WHERE event_type = 'wecom_click')::bigint AS wecom_clicks,
      COUNT(*) FILTER (WHERE event_type = 'lead_submit')::bigint AS lead_submits,
      MAX(created_at) AS last_event_at
    FROM filtered
    GROUP BY source, medium, campaign
  )
  SELECT jsonb_build_object(
    'from', p_from,
    'to', p_to,
    'totals', COALESCE((SELECT to_jsonb(t) FROM totals t), '{}'::jsonb),
    'channels', COALESCE(
      (
        SELECT jsonb_agg(to_jsonb(c) ORDER BY c.visitors DESC, c.wecom_clicks DESC, c.lead_submits DESC)
        FROM channels c
      ),
      '[]'::jsonb
    )
  )
  INTO result;

  RETURN result;
END;
$$;

REVOKE ALL ON FUNCTION public.admin_get_landing_conversion_stats(timestamptz, timestamptz) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.admin_get_landing_conversion_stats(timestamptz, timestamptz) TO authenticated;

COMMENT ON TABLE public.landing_conversion_events IS
  'HMS /home 投放落地页匿名访问、企微点击与表单成功事件；仅平台管理员可读。';

COMMENT ON FUNCTION public.admin_get_landing_conversion_stats(timestamptz, timestamptz) IS
  '平台管理员按时间范围读取 HMS 官网 UV、企微点击、表单提交及渠道聚合。';
