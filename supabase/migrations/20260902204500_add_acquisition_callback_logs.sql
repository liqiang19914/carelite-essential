CREATE TABLE IF NOT EXISTS public.acquisition_wecom_callback_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stage text NOT NULL,
  event_name text NOT NULL DEFAULT '',
  change_type text NOT NULL DEFAULT '',
  tracking_token text NOT NULL DEFAULT '',
  reason text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS acquisition_callback_logs_created_idx
  ON public.acquisition_wecom_callback_logs (created_at DESC);

ALTER TABLE public.acquisition_wecom_callback_logs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.acquisition_wecom_callback_logs FROM anon, authenticated;

