CREATE TABLE IF NOT EXISTS public.acquisition_integration_settings (
  singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
  wecom_enabled boolean NOT NULL DEFAULT false,
  wecom_corp_id text NOT NULL DEFAULT '',
  wecom_callback_token text NOT NULL,
  wecom_callback_aes_key text NOT NULL,
  wecom_acquisition_url text NOT NULL DEFAULT 'https://work.weixin.qq.com/ca/cawcdec92a981adaef',
  wecom_callback_verified_at timestamptz,
  baidu_enabled boolean NOT NULL DEFAULT false,
  baidu_token text NOT NULL DEFAULT '',
  baidu_form_new_type integer NOT NULL DEFAULT 3,
  baidu_wecom_new_type integer NOT NULL DEFAULT 79,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.acquisition_attribution_sessions (
  tracking_token text PRIMARY KEY CHECK (tracking_token ~ '^hms_[A-Za-z0-9_-]{12,48}$'),
  visitor_id text NOT NULL CHECK (char_length(visitor_id) BETWEEN 8 AND 100),
  session_id text NOT NULL UNIQUE CHECK (char_length(session_id) BETWEEN 8 AND 100),
  landing_url text NOT NULL DEFAULT '',
  bd_vid text NOT NULL DEFAULT '',
  utm_source text NOT NULL DEFAULT 'direct',
  utm_medium text NOT NULL DEFAULT '',
  utm_campaign text NOT NULL DEFAULT '',
  utm_content text NOT NULL DEFAULT '',
  utm_term text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL DEFAULT (now() + interval '90 days')
);

CREATE INDEX IF NOT EXISTS acquisition_attribution_bd_vid_idx
  ON public.acquisition_attribution_sessions (bd_vid)
  WHERE bd_vid <> '';

CREATE INDEX IF NOT EXISTS acquisition_attribution_expires_idx
  ON public.acquisition_attribution_sessions (expires_at);

CREATE TABLE IF NOT EXISTS public.acquisition_conversion_reports (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tracking_token text NOT NULL REFERENCES public.acquisition_attribution_sessions(tracking_token) ON DELETE CASCADE,
  event_type text NOT NULL CHECK (event_type IN ('lead_submit', 'wecom_added')),
  new_type integer NOT NULL,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'success', 'failed', 'skipped')),
  attempts integer NOT NULL DEFAULT 0,
  logid_url text NOT NULL DEFAULT '',
  baidu_response jsonb,
  error_message text NOT NULL DEFAULT '',
  external_user_id text NOT NULL DEFAULT '',
  wecom_user_id text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  last_attempted_at timestamptz,
  reported_at timestamptz,
  UNIQUE (tracking_token, event_type)
);

CREATE INDEX IF NOT EXISTS acquisition_conversion_reports_created_idx
  ON public.acquisition_conversion_reports (created_at DESC);

